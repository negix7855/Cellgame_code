# =========================
# 背景画像に描かれたキーボード
# （objects.keyboard.Keyboard と同じく、押されたキーの文字を返す。描画は背景画像に任せる）
# =========================

class ImageKeyboard:

    def __init__(self, key_rects, font, width=BASE_WIDTH, height=BASE_HEIGHT):
        """key_rects: {キーの文字: (x, y, w, h)}（基準サイズの座標）"""
        self.key_rects = key_rects
        self.font = font

        # 当たり判定だけのボタン（描画はしない）
        self.key_buttons = [Button(0, 0, 0, 0, label, font) for label in key_rects]

        self.update_layout(width, height)

    def update_layout(self, width, height):
        for button in self.key_buttons:
            button.rect = scale_rect(self.key_rects[button.text], width, height)

    def handle_event(self, event):
        """押されたキーの文字列を返す（押されていなければ None）"""
        if event.type != pygame.MOUSEBUTTONDOWN or event.button != 1:
            return None

        for button in self.key_buttons:
            if button.clicked(event.pos):
                return button.text

        return None

    def draw(self, screen, debug=False):
        """キーは背景画像に描かれているので何もしない（debug なら当たり判定を赤枠で表示）"""
        if debug:
            for button in self.key_buttons:
                pygame.draw.rect(screen, (255, 0, 0), button.rect, 2)


def scale_rect(rect, width, height):
    """基準サイズの座標を、画面サイズに合わせて変換する"""
    x, y, w, h = rect
    sx = width / BASE_WIDTH
    sy = height / BASE_HEIGHT

    return pygame.Rect(x * sx, y * sy, w * sx, h * sy)
